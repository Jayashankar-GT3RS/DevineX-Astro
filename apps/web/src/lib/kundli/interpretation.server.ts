/**
 * AI interpretation engine for Kundli reports.
 *
 * Sends the validated astronomical calculation data to Groq (server-side) as
 * the sole source of chart facts, and asks for a structured Vedic report. The
 * model is explicitly forbidden from inventing planetary positions, yogas or
 * doshas, or presenting astrology as scientifically proven.
 *
 * This is a server-side generation job, not a visitor chat: only structured
 * calculation data is sent — never uploaded documents, email or name.
 */
import { generateGroqText, groqModel } from './groq.server';
import type { KundliCalculationData, InterpretationReport } from './types';

const SYSTEM_PROMPT = `You are a knowledgeable Vedic astrology (Jyotish) report writer for DevineX Astro.

You will receive validated astronomical birth-chart calculation data as JSON. This data is the SOLE source of astronomical and chart-specific facts. You must use ONLY these calculations.

Rules:
- Write in clear, respectful, easy-to-understand Indian English.
- Generate personalized traditional Vedic interpretations using the supplied planetary placements, signs, houses, Nakshatras, Dashas and validated combinations ONLY.
- NEVER invent missing calculations, Yogas, Doshas or planetary placements that are not present in the supplied data.
- Do NOT present astrology as a scientifically validated predictive method or guarantee future outcomes.
- Avoid deterministic claims about death, serious illness, pregnancy, divorce, financial gains or other consequential personal events.
- Clearly distinguish traditional astrological interpretations from established facts.
- Include uncertainty and limitations where birth details or calculation methods affect interpretations.
- Do not prescribe gemstones, paid rituals or services as necessary to prevent harm. Suggestions must be optional and reflective.
- The birth time may be approximate. Where that makes the ascendant or house placements uncertain, say so instead of presenting them as exact.

Output format:
Return the report as a sequence of sections. Begin each section with a line "## SECTION TITLE" exactly, followed by the section body. Use the exact section titles requested, in the order requested. Write at least one substantial paragraph per section. Do not add sections that were not requested. If the data for a requested section is genuinely unavailable, write a brief note saying so instead of inventing it.`;

export const REQUESTED_SECTIONS = [
	'Basic Birth Chart Overview',
	'Ascendant (Lagna) Interpretation',
	'Moon Sign and Nakshatra',
	'Planetary Positions and Interpretations',
	'Personality and Characteristics',
	'Career and Professional Life',
	'Relationships and Marriage',
	'Financial Aspects',
	'General Life Insights',
	'Yoga Analysis',
	'Dosha Analysis',
	'Mahadasha and Antardasha',
	'Traditional Guidance',
	'Summary',
] as const;

/** Strips markdown emphasis and numbering a model may add to a heading. */
function normalizeTitle(raw: string): string {
	return raw
		.replace(/^#{1,6}\s*/, '')
		.replace(/^\d+[.)]\s*/, '')
		.replace(/\*\*/g, '')
		.replace(/\s+/g, ' ')
		.trim();
}

/** Parses the model's "## SECTION TITLE" output into structured sections. */
export function parseSections(text: string): { title: string; body: string }[] {
	const sections: { title: string; body: string }[] = [];
	const blocks = text.split(/^\s*##\s+/m);

	for (const block of blocks) {
		const trimmed = block.trim();
		if (!trimmed) continue;

		const newline = trimmed.indexOf('\n');
		const title = normalizeTitle(newline === -1 ? trimmed : trimmed.slice(0, newline));
		const body = newline === -1 ? '' : trimmed.slice(newline + 1).trim();
		if (!title || !body) continue;

		sections.push({ title, body });
	}

	return sections;
}

export interface InterpretationOptions {
	/** Groq model ID; defaults to GROQ_MODEL or the built-in default. */
	model?: string;
}

/**
 * The current and next two Vimshottari mahadashas, with antardashas, as of the
 * chart's reference date. Sending all nine periods plus every antardasha adds
 * thousands of tokens and pushes the request past Groq's per-minute limit on
 * smaller plans; three periods are enough for current/upcoming guidance.
 */
function summarizeDashas(calc: KundliCalculationData) {
	const asOf = new Date(calc.referenceDate).getTime();
	const currentIndex = calc.dashas.findIndex(
		(dasha) => new Date(dasha.start).getTime() <= asOf && asOf < new Date(dasha.end).getTime(),
	);
	const startIndex = currentIndex >= 0 ? currentIndex : 0;

	return calc.dashas.slice(startIndex, startIndex + 3).map(dasha => ({
		lord: dasha.lord,
		start: dasha.start,
		end: dasha.end,
		antardashas: dasha.antardashas,
	}));
}

/**
 * Builds the compact chart payload sent to Groq. Everything the text can claim
 * must appear here; nothing here is generated by the model.
 */
function buildChartSummary(calc: KundliCalculationData) {
	return {
		customerNote:
			'Use ONLY the following validated calculation data. Do not invent any planetary position, yoga or dosha not listed here.',
		birthDetails: {
			birthplace: calc.birthplaceName,
			latitude: calc.latitude,
			longitude: calc.longitude,
			timezone: calc.timezone,
			utcTime: calc.utcTime,
			birthTimeAccuracy: calc.birthTimeAccuracy,
		},
		calculationSettings: {
			engine: calc.engineName,
			engineVersion: calc.engineVersion,
			ayanamsa: calc.ayanamsa,
			ayanamsaValue: calc.ayanamsaValue,
			chartStyle: calc.chartStyle,
			houseSystem: calc.houseSystem,
		},
		ascendant: calc.ascendant,
		moonSign: calc.moonSign,
		sunSign: calc.sunSign,
		janmaNakshatra: calc.janmaNakshatra,
		nakshatraPada: calc.nakshatraPada,
		planets: calc.planets.map(p => ({
			name: p.name,
			sign: p.sign,
			degreeInSign: p.degreeInSign,
			house: p.house,
			nakshatra: p.nakshatra,
			pada: p.pada,
			retrograde: p.retrograde,
			dignity: p.dignity,
			navamsaSign: p.navamsaSign,
		})),
		houses: calc.houses.map(house => ({ house: house.index, sign: house.sign })),
		dashas: summarizeDashas(calc),
		yogas: calc.yogas,
		doshas: calc.doshas,
		transits: calc.transits,
		referenceDate: calc.referenceDate,
		limitations: calc.limitations,
	};
}

/**
 * Generates the AI interpretation report from validated calculation data.
 * Returns structured sections plus the raw text for storage and PDF rendering.
 */
export async function generateInterpretation(
	calc: KundliCalculationData,
	options: InterpretationOptions = {},
): Promise<InterpretationReport> {
	const model = options.model ?? groqModel();

	const userMessage = [
		'Write a personalized Vedic Kundli interpretation report using the validated calculation data below.',
		'Produce exactly these sections, in this order, each starting with "## " followed by the title:',
		...REQUESTED_SECTIONS.map(section => `## ${section}`),
		'',
		'Guidance:',
		'- Basic Birth Chart Overview: ascendant, Moon sign, Sun sign, Janma Nakshatra and house layout as supplied.',
		'- Ascendant (Lagna) Interpretation: the ascendant sign, its Nakshatra/pada and the 1st house.',
		'- Moon Sign and Nakshatra: the Moon sign and Janma Nakshatra, including pada.',
		'- Planetary Positions and Interpretations: each planet in the table — sign, house, Nakshatra, dignity, retrograde state.',
		'- Personality, Career, Relationships, Financial Aspects, General Life Insights: derive these only from supplied placements, houses, yogas, doshas and dashas.',
		'- Yoga and Dosha Analysis: include ONLY the listed yogas/doshas; if none, say no validated combinations were identified for this chart.',
		'- Mahadasha and Antardasha: name the currently running mahadasha and antardasha as of referenceDate from the supplied dates, then the next period.',
		'- Traditional Guidance: optional, reflective; no paid remedies. Summary: concise closing overview.',
		'',
		'CALCULATION DATA (JSON):',
		JSON.stringify(buildChartSummary(calc)),
	].join('\n');

	const rawText = await generateGroqText({ system: SYSTEM_PROMPT, user: userMessage, model });
	const sections = parseSections(rawText);

	if (sections.length === 0) {
		// The model replied without the requested headings: keep the report rather
		// than failing the whole generation, but make the missing structure clear.
		return {
			sections: [{ title: 'Kundli Interpretation', body: rawText }],
			rawText,
		};
	}

	return { sections, rawText };
}
